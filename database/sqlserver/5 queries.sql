-- สิ่งที่เพิ่ม: ชื่อเรื่อง ประเภทคำสั่ง คำถามที่ตอบ หลักการทำงาน การนำไปใช้ และข้อสังเกต
-- ตัวคำสั่ง SQL ทั้ง 10 ข้อคงเดิมจาก 05_queries.sql
-- สัดส่วน: JOIN >=3 ตาราง 2 ข้อ, GROUP BY + HAVING 3 ข้อ,
--          Subqueries 3 ข้อ, Window Functions 2 ข้อ
-- วิธีใช้: ใช้แทน queries.sql หรือ 05_queries.sql ฉบับเดิมในชุดส่งงาน เลือกชื่อเดียว
-- เปิดด้วย SSMS เลือกฐานข้อมูล washy_realistic แล้วรันทีละข้อหรือรันทั้งหมด
-- คำสั่งในไฟล์เป็นการอ่านข้อมูล ไม่เพิ่ม แก้ไข หรือลบข้อมูล

USE washy_realistic;
GO
-- ======================================================================
-- ข้อ 1: แสดงรายการจองพร้อมข้อมูลลูกค้า รถ และแพ็กเกจ
-- ประเภท: Multi-table JOIN จำนวน 4 ตาราง
-- คำถามที่ตอบ: การจองแต่ละรายการเป็นของลูกค้าคนใด ใช้รถและแพ็กเกจใด และมีสถานะอะไร
-- หลักการทำงาน: เชื่อม bookings, vehicles, customers และ service_packages ด้วย Foreign Key
-- การนำไปใช้: ใช้ประกอบหน้ารายการจอง เพื่อให้พนักงานตรวจสอบข้อมูลที่เกี่ยวข้องในครั้งเดียว
-- ข้อสังเกต: แสดงชื่อลูกค้าเฉพาะ first_name และแสดงการจองทุกสถานะ
-- ======================================================================
SELECT b.booking_id,c.first_name,v.license_plate,p.package_name,b.start_time,b.booking_status FROM dbo.bookings b JOIN dbo.vehicles v ON v.vehicle_id=b.vehicle_id JOIN dbo.customers c ON c.customer_id=v.customer_id JOIN dbo.service_packages p ON p.package_id=b.package_id;

-- ======================================================================
-- ข้อ 2: แสดงวัสดุและต้นทุนที่ใช้ในแต่ละงานบริการ
-- ประเภท: Multi-table JOIN จำนวน 4 ตาราง
-- คำถามที่ตอบ: งานบริการแต่ละรายการใช้วัสดุอะไร ปริมาณเท่าใด และมีต้นทุนวัสดุเท่าใด
-- หลักการทำงาน: เชื่อม material_usage, materials, bookings และ vehicles แล้วคำนวณ quantity_used * unit_cost_snapshot
-- การนำไปใช้: ใช้ตรวจสอบการเบิกวัสดุและต้นทุนรายรายการของงานบริการ
-- ข้อสังเกต: ผลลัพธ์เป็นต้นทุนแต่ละรายการเบิก ไม่ใช่ต้นทุนรวมทั้งงาน และใช้ต้นทุนที่บันทึกขณะเบิก
-- ======================================================================
SELECT b.booking_id,v.license_plate,m.material_name,u.quantity_used,u.quantity_used*u.unit_cost_snapshot material_cost FROM dbo.material_usage u JOIN dbo.materials m ON m.material_id=u.material_id JOIN dbo.bookings b ON b.booking_id=u.booking_id JOIN dbo.vehicles v ON v.vehicle_id=b.vehicle_id;

-- ======================================================================
-- ข้อ 3: ค้นหาแพ็กเกจที่มีงานเสร็จอย่างน้อย 10 รายการ
-- ประเภท: GROUP BY และ HAVING
-- คำถามที่ตอบ: แพ็กเกจใดมีจำนวนงานบริการสำเร็จตั้งแต่ 10 รายการขึ้นไป
-- หลักการทำงาน: กรอง Completed จัดกลุ่มตาม package_id และใช้ HAVING COUNT(*)>=10
-- การนำไปใช้: ใช้ระบุแพ็กเกจที่มีการใช้บริการถึงเกณฑ์ เพื่อประกอบการวางแผนบริการหรือโปรโมชัน
-- ข้อสังเกต: นับจำนวนงานที่เสร็จทั้งหมดในข้อมูล ไม่จำกัดช่วงเวลาและไม่ใช่จำนวนลูกค้าไม่ซ้ำ
-- ======================================================================
SELECT package_id,COUNT(*) completed_jobs FROM dbo.bookings WHERE booking_status='Completed' GROUP BY package_id HAVING COUNT(*)>=10;

-- ======================================================================
-- ข้อ 4: ค้นหาลูกค้าที่ใช้บริการสำเร็จมากกว่า 5 ครั้ง
-- ประเภท: GROUP BY และ HAVING
-- คำถามที่ตอบ: ลูกค้าคนใดมีประวัติใช้บริการสำเร็จมากกว่า 5 ครั้ง
-- หลักการทำงาน: เชื่อม bookings กับ vehicles จัดกลุ่มตาม customer_id และใช้ HAVING COUNT(*)>5
-- การนำไปใช้: ใช้ค้นหาลูกค้าที่กลับมาใช้บริการบ่อย เพื่อพิจารณาสิทธิพิเศษหรือแพ็กเกจสมาชิก
-- ข้อสังเกต: รวมรถทุกคันของลูกค้าคนเดียวกัน และนับเฉพาะ Completed
-- ======================================================================
SELECT v.customer_id,COUNT(*) visits FROM dbo.bookings b JOIN dbo.vehicles v ON v.vehicle_id=b.vehicle_id WHERE booking_status='Completed' GROUP BY v.customer_id HAVING COUNT(*)>5;

-- ======================================================================
-- ข้อ 5: ค้นหาวันที่มียอดรับชำระมากกว่า 1,000 บาท
-- ประเภท: GROUP BY และ HAVING
-- คำถามที่ตอบ: วันใดมียอดรับชำระที่ไม่ใช่สิทธิสมาชิกมากกว่า 1,000 บาท
-- หลักการทำงาน: กรองวิธีชำระที่ไม่ใช่ Member_Credit รวม amount ตามวันที่ payment_date และใช้ HAVING SUM(amount)>1000
-- การนำไปใช้: ใช้สรุปวันที่มียอดรับชำระถึงเกณฑ์ เพื่อประกอบรายงานการรับชำระรายวัน
-- ข้อสังเกต: รวม Cash, PromptPay และ Credit_Card โดยยึดวันที่ชำระ ไม่ใช่วันที่เริ่มบริการ
-- ======================================================================
SELECT CONVERT(date,payment_date) paid_date,SUM(amount) cash_received FROM dbo.payments WHERE payment_method<>'Member_Credit' GROUP BY CONVERT(date,payment_date) HAVING SUM(amount)>1000;

-- ======================================================================
-- ข้อ 6: ค้นหาแพ็กเกจที่มีราคาสูงกว่าราคาเฉลี่ย
-- ประเภท: Subquery
-- คำถามที่ตอบ: แพ็กเกจใดมีราคาสูงกว่าราคาเฉลี่ยของแพ็กเกจทั้งหมด
-- หลักการทำงาน: คำสั่งย่อยคำนวณ AVG(price) แล้วคำสั่งหลักเลือกแพ็กเกจที่ price สูงกว่าค่านั้น
-- การนำไปใช้: ใช้เปรียบเทียบระดับราคาบริการ และประกอบการพิจารณาตั้งราคา
-- ข้อสังเกต: คำนวณจากทุกแพ็กเกจ รวมแพ็กเกจที่ไม่ได้เปิดใช้งาน เพราะไม่ได้กรอง status
-- ======================================================================
SELECT * FROM dbo.service_packages WHERE price>(SELECT AVG(price) FROM dbo.service_packages);

-- ======================================================================
-- ข้อ 7: ค้นหาลูกค้าที่ยังไม่มีประวัติใช้บริการสำเร็จ
-- ประเภท: Correlated Subquery และ NOT EXISTS
-- คำถามที่ตอบ: ลูกค้าคนใดยังไม่มีรถที่เคยรับบริการจนเสร็จ
-- หลักการทำงาน: ตรวจแต่ละ customer_id ด้วย NOT EXISTS ผ่าน vehicles และ bookings สถานะ Completed
-- การนำไปใช้: ใช้ระบุกลุ่มลูกค้าที่ลงทะเบียนแล้วแต่ยังไม่เคยใช้บริการสำเร็จ เพื่อวางแผนเชิญกลับมาใช้บริการ
-- ข้อสังเกต: อาจเป็นลูกค้าที่ไม่มีรถ ไม่มีการจอง หรือมีเพียงคิว Pending, In_Progress หรือ Cancelled
-- ======================================================================
SELECT c.* FROM dbo.customers c WHERE NOT EXISTS(SELECT 1 FROM dbo.vehicles v JOIN dbo.bookings b ON b.vehicle_id=v.vehicle_id WHERE v.customer_id=c.customer_id AND b.booking_status='Completed');

-- ======================================================================
-- ข้อ 8: ค้นหารายการเบิกวัสดุที่มากกว่าปริมาณเฉลี่ยของวัสดุนั้น
-- ประเภท: Correlated Subquery
-- คำถามที่ตอบ: รายการใดเบิกวัสดุมากกว่าปริมาณเฉลี่ยต่อรายการของวัสดุชนิดเดียวกัน
-- หลักการทำงาน: คำสั่งย่อยคำนวณ AVG(quantity_used) เฉพาะ material_id ที่ตรงกับแถวหลัก แล้วเปรียบเทียบปริมาณ
-- การนำไปใช้: ใช้คัดเลือกรายการเบิกเพื่อให้พนักงานตรวจสอบเหตุผลหรือความเหมาะสมของปริมาณ
-- ข้อสังเกต: การใช้มากกว่าค่าเฉลี่ยไม่ได้แปลว่าผิดปกติเสมอไป เพราะงานบริการอาจมีความต้องการต่างกัน
-- ======================================================================
SELECT u.* FROM dbo.material_usage u WHERE quantity_used>(SELECT AVG(x.quantity_used) FROM dbo.material_usage x WHERE x.material_id=u.material_id);

-- ======================================================================
-- ข้อ 9: จัดอันดับแพ็กเกจตามมูลค่าบริการรวม
-- ประเภท: Window Function ด้วย RANK และ OVER
-- คำถามที่ตอบ: แพ็กเกจใดมีมูลค่าบริการจากงานที่เสร็จสูงที่สุด
-- หลักการทำงาน: กรอง Completed รวม price_snapshot ตาม package_id และ RANK จากยอดรวมมากไปน้อย
-- การนำไปใช้: ใช้เปรียบเทียบมูลค่าบริการของแต่ละแพ็กเกจ เพื่อประกอบการวางแผนการขาย
-- ข้อสังเกต: ยอดรวมครอบคลุมทั้งการรับชำระทั่วไปและการใช้สิทธิสมาชิก ยอดเท่ากันได้อันดับเดียวกันและอันดับถัดไปอาจข้าม
-- ======================================================================
SELECT package_id,SUM(price_snapshot) service_value,RANK() OVER(ORDER BY SUM(price_snapshot) DESC) revenue_rank FROM dbo.bookings WHERE booking_status='Completed' GROUP BY package_id;

-- ======================================================================
-- ข้อ 10: แสดงรายการจองล่าสุดของรถแต่ละคัน
-- ประเภท: Window Function ด้วย ROW_NUMBER และ OVER
-- คำถามที่ตอบ: รถแต่ละคันมีการจองใดที่มีเวลาเริ่มบริการล่าสุด
-- หลักการทำงาน: ใช้ ROW_NUMBER แบ่งกลุ่มตาม vehicle_id เรียง start_time DESC, booking_id DESC แล้วเลือก rn=1
-- การนำไปใช้: ใช้แสดงข้อมูลคิวล่าสุดตามเวลาเริ่มบริการของรถแต่ละคัน เพื่อประกอบการตรวจสอบประวัติและคิว
-- ข้อสังเกต: อาจได้คิวในอนาคตหรือรายการยกเลิก เพราะไม่กรองสถานะ และรถที่ไม่มีการจองจะไม่ปรากฏ
-- ======================================================================
WITH ranked AS(SELECT *,ROW_NUMBER() OVER(PARTITION BY vehicle_id ORDER BY start_time DESC,booking_id DESC) rn FROM dbo.bookings) SELECT * FROM ranked WHERE rn=1;
